class Icons:
    def __init__(self, root):
        self.root = root
        self.cache = {}

    def get(self, name, color="#28554e", size=17):
        size = max(12, round(size * self.root.winfo_fpixels("1i") / 96))
        key = name, color, size
        if key not in self.cache:
            scale = 5
            image = Image.new("RGBA", (24*scale, 24*scale))
            draw = ImageDraw.Draw(image)
            if name == "brand":
                draw.rounded_rectangle((0, 0, 24*scale-1, 24*scale-1), radius=5*scale,
                                       fill="#286554")
                color = "#f7f4df"
            for path in PATHS["book" if name == "brand" else name]:
                points = [(x*scale,y*scale) for x,y in path]
                draw.line(points, fill=color, width=2*scale, joint="curve")
            if name == "brand":
                draw.polygon([(15*scale,5*scale),(18*scale,4*scale),(18*scale,12*scale),
                              (16.5*scale,10.5*scale),(15*scale,12*scale)], fill="#f9c56c")
            image = image.resize((size, size), Image.Resampling.LANCZOS)
            self.cache[key] = ImageTk.PhotoImage(image, master=self.root)
        return self.cache[key]
